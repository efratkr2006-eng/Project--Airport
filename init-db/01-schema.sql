CREATE TABLE EMPLOYEE
(
  EmployeeID INT NOT NULL,
  FirstName INT NOT NULL,
  LastName INT NOT NULL,
  Role INT NOT NULL,
  HireDate INT NOT NULL,
  PRIMARY KEY (EmployeeID)
);

CREATE TABLE AIRPLANE
(
  AirplaneID INT NOT NULL,
  Capacity INT NOT NULL,
  ManufacturingYear INT NOT NULL,
  Model INT NOT NULL,
  Manufacturer INT NOT NULL,
  PRIMARY KEY (AirplaneID)
);

CREATE TABLE CHECK
(
  CheckID INT NOT NULL,
  CheckDate INT NOT NULL,
  CheckType INT NOT NULL,
  CheckResultJSON INT NOT NULL,
  NextCheckDate INT NOT NULL,
  EmployeeID INT NOT NULL,
  AirplaneID INT NOT NULL,
  PRIMARY KEY (CheckID),
  FOREIGN KEY (EmployeeID) REFERENCES EMPLOYEE(EmployeeID),
  FOREIGN KEY (AirplaneID) REFERENCES AIRPLANE(AirplaneID)
);

CREATE TABLE HAZARD
(
  HazardID INT NOT NULL,
  HazardType INT NOT NULL,
  RiskLevel INT NOT NULL,
  Location INT NOT NULL,
  HazardDetailsJSON INT,
  PRIMARY KEY (HazardID)
);

CREATE TABLE CORRECTIVEACTION
(
  ActionID INT NOT NULL,
  ActionDescription INT NOT NULL,
  RecoveryTime INT NOT NULL,
  State INT NOT NULL,
  Duration INT NOT NULL,
  HazardID INT NOT NULL,
  EmployeeID INT NOT NULL,
  PRIMARY KEY (ActionID),
  FOREIGN KEY (HazardID) REFERENCES HAZARD(HazardID),
  FOREIGN KEY (EmployeeID) REFERENCES EMPLOYEE(EmployeeID)
);

CREATE TABLE FLIGHT
(
  FlightID INT NOT NULL,
  FlightDate INT NOT NULL,
  Departure INT NOT NULL,
  Destination INT NOT NULL,
  Duration INT NOT NULL,
  AirplaneID INT NOT NULL,
  PRIMARY KEY (FlightID),
  FOREIGN KEY (AirplaneID) REFERENCES AIRPLANE(AirplaneID)
);

CREATE TABLE IDENTIFIES
(
  CheckID INT NOT NULL,
  HazardID INT NOT NULL,
  PRIMARY KEY (CheckID, HazardID),
  FOREIGN KEY (CheckID) REFERENCES CHECK(CheckID),
  FOREIGN KEY (HazardID) REFERENCES HAZARD(HazardID)
);